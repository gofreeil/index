/* אין \b בתבניות: בעברית הוא אינו מתפקד כגבול מילה ב-JS.
   "גוש עציון" נבדק לפני "גוש דן", ו"עמק יזרעאל" לפני "צפון". */
const REGION_PATTERNS = /** @type {[RegExp, string][]} */ ([
	[/גוש עציון/, 'etzion'],
	[/עמק יזרעאל/, 'jezreel'],
	[/גוש דן/, 'dan'],
	[/שרון/, 'sharon'],
	[/שפלה/, 'shfela'],
	[/נגב|דרום/, 'south'],
	[/גליל|צפון/, 'north'],
	[/מרכז/, 'center']
]);

const COUNTRY_RE = /ארצי|כל הארץ|בכל הארץ|כל מקום בארץ|משלוח חינם/;
const GLOBAL_RE = /כל העולם|והעולם|ובעולם|בעולם|לעולם|חו"ל|חו״ל/;
/* "ארצי (מלבד אילת)" — היישוב נזכר כדי להוציא אותו, לא כדי לתחום. */
const EXCLUDE_RE = /מלבד|למעט|חוץ מ|פרט ל/;
const WIDE_RE = /והסביבה|הסביבה|אזור|איזור|עד /;

const clean = (/** @type {unknown} */ v) =>
	String(v ?? '')
		.replace(/\s+/g, ' ')
		.trim();

/* מהארוך לקצר, כדי ש"מגדל העמק" לא ייחתך ל"מגדל" ו"קרית גת" לא תיקרא "גת". */
const CITIES_BY_LENGTH = Object.keys(CITY_LATLNG).sort((a, b) => b.length - a.length);

/** @param {string} text @returns {string[]} */
function findCities(text) {
	let rest = text;
	/** @type {string[]} */
	const out = [];
	for (const c of CITIES_BY_LENGTH) {
		if (!rest.includes(c)) continue;
		out.push(c);
		rest = rest.split(c).join(' ');
	}
	return out;
}

/** @param {string} text */
function scanGeo(text) {
	const cities = EXCLUDE_RE.test(text) && COUNTRY_RE.test(text) ? [] : findCities(text);
	// כל האזורים שנזכרו, לא רק הראשון — "דרום, מרכז ואון ליין" הוא שניהם.
	let rest = text;
	for (const c of cities) rest = rest.split(c).join(' ');
	const regions = REGION_PATTERNS.filter(([re]) => re.test(rest)).map(([, k]) => k);
	return { cities, regions };
}

/**
 * אזור העבודה של כרטיסייה אחת.
 * סדר ההכרעה: גיאוגרפיה מפורשת ב"אזור מכירה" → "כל הארץ"/"כל העולם" →
 * נפילה לכתובת/עיר. הנפילה היא שמצילה את מי שכתב "קליניקה" אבל מילא כתובת.
 *
 * kind: city | cities | region | country | global | none
 * @param {{ salesArea?: string, sales_area?: string, address?: string, city?: string,
 *           branches?: {city?: string, address?: string}[] }} b
 */
export function resolveServiceArea(b) {
	const raw = clean(b.salesArea ?? b.sales_area);
	// סניפים ומקומות שירות נוספים הם מיקומים פיזיים מוצהרים, לא ניסוח חופשי
	const branchText = clean(branchesGeoText(b.branches));
	const base = { cities: /** @type {string[]} */ ([]), regions: /** @type {string[]} */ ([]) };

	let { cities, regions } = scanGeo(raw);
	let fromAddress = false;

	if (!cities.length && !regions.length) {
		if (GLOBAL_RE.test(raw)) return { ...base, kind: 'global', label: 'כל הארץ והעולם' };
		if (COUNTRY_RE.test(raw)) return { ...base, kind: 'country', label: 'כל הארץ' };
		({ cities, regions } = scanGeo(
			clean([b.city, b.address, branchText].filter(Boolean).join(' '))
		));
		fromAddress = cities.length > 0 || regions.length > 0;
	} else if (branchText) {
		// "אזור מכירה" שכבר תיאר גיאוגרפיה לא מבטל סניף שנרשם בנפרד
		for (const c of findCities(branchText)) if (!cities.includes(c)) cities.push(c);
	}

	if (!cities.length && !regions.length) return { ...base, kind: 'none', label: '' };

	const wide = !fromAddress && WIDE_RE.test(raw);
	const names = [...cities, ...regions.map((k) => REGIONS[k].label)];
	return {
		cities,
		regions,
		wide,
		kind: names.length > 1 ? 'cities' : cities.length ? 'city' : 'region',
		label: names.join(', ') + (wide && names.length === 1 && cities.length ? ' והסביבה' : '')
	};
}

/* יישוב בודד ~8 ק"מ; "והסביבה"/"אזור" מרחיב ל-20; כמה יישובים = פעילות
   פרושה, ולכן כל אחד מקבל עיגול בינוני שנפגש עם שכניו. */
const CITY_RADIUS = 8000;
const WIDE_RADIUS = 20000;
const MULTI_RADIUS = 14000;

/**
 * העיגולים שמצויירים עבור כרטיסייה. ריק עבור ארצי/עולמי (עיגול כזה היה
 * מכסה את כל המפה) ועבור מי שאין לו שום גיאוגרפיה.
 * @param {ReturnType<typeof resolveServiceArea>} area
 * @returns {{lat:number, lng:number, radius:number}[]}
 */
export function serviceCircles(area) {
	if (area.kind === 'country' || area.kind === 'global' || area.kind === 'none') return [];
	const radius = area.cities.length > 1 ? MULTI_RADIUS : area.wide ? WIDE_RADIUS : CITY_RADIUS;
	/** @type {{lat:number, lng:number, radius:number}[]} */
	const out = [];
	for (const key of area.regions)
		for (const [lat, lng, r] of REGIONS[key].circles) out.push({ lat, lng, radius: r });
	for (const name of area.cities) {
		const ll = CITY_LATLNG[name];
		if (ll) out.push({ lat: ll[0], lng: ll[1], radius });
	}
	return out;
}
