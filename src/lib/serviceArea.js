/**
 * הצורות שמצוירות עבור כרטיסייה, כל אחת עם התווית שלה — עיגול של סניף
 * נושא את שם היישוב שלו גם כשהאזור המוצהר הוא "כל הארץ".
 *
 * key מזהה צורה זהה בין כרטיסיות שונות, כדי שהמפה תמזג אותן לצורה אחת
 * במקום לערום שכבות שמכהות זו את זו.
 *
 * @param {ReturnType<typeof resolveServiceArea>} area
 * @returns {Shape[]}
 */
export function serviceShapes(area) {
	/** @type {Shape[]} */
	const out = [];

	// ארצי ועולמי חולקים צורה אחת (key זהה), ולכן היא מצוירת פעם אחת עם
	// פופאפ שמונה את כולם, ולא 62 מתארים זה על גבי זה.
	//
	// מי שלא ניתן היה לגזור ממנו שום מקום אינו מקבל כאן דבר. קודם צויר גם
	// הוא כמדינה שלמה, וזו הייתה טענה שאיש לא מסר: חמישית מהכרטיסיות —
	// רובן כאלה שכתבו "אזור ספציפי, אפרט בהערות" — הוצגו כעסק ארצי. עדיף
	// בלי מפה מאשר מפה שמסמנת את כל ישראל למי שלא כתב על עצמו כלום.
	if (area.kind === 'country' || area.kind === 'global') {
		out.push({ type: 'country', key: 'country', label: 'כל הארץ', ...COUNTRY_CIRCLE });
	}

	// כל יישוב נמדד לפי גודלו, בין שהוא לבדו ובין שהוא אחד מכמה; רק
	// "והסביבה" מוסיף לו מרחק, וגם אז ההפרש בין הערים נשמר
	const extra = area.wide ? WIDE_EXTRA : 0;
	for (const key of area.regions)
		for (const [lat, lng, r] of REGIONS[key].circles)
			out.push({
				type: 'circle',
				key: `${lat}|${lng}|${r}`,
				lat,
				lng,
				radius: r,
				label: REGIONS[key].label
			});
	for (const name of area.cities) {
		const ll = CITY_LATLNG[name];
		if (!ll) continue;
		const radius = (CITY_SPAN[name] || DEFAULT_CITY_SPAN) + extra;
		out.push({
			type: 'circle',
			key: `${ll[0]}|${ll[1]}|${radius}`,
			lat: ll[0],
			lng: ll[1],
			radius,
			label: name
		});
	}
	return out;
}

/**
 * האם יש בכלל מה לצייר לכרטיסייה הזאת — נקודה מדויקת, או צורת אזור אחת
 * לפחות. אין: הדף לא מציג מפה כלל, במקום להציג מפה ריקה של כל הארץ.
 *
 * @param {Parameters<typeof resolveServiceArea>[0] & {lat?: unknown, lng?: unknown}} b
 */
export function hasServiceMap(b) {
	if (typeof b?.lat === 'number' && typeof b?.lng === 'number') return true;
	return serviceShapes(resolveServiceArea(b)).length > 0;
}
