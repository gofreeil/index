/* התאמה מהארוך לקצר, כדי ש"מגדל העמק" ייקלט כשמו ולא ייחתך ל"מגדל",
   ו"טירת כרמל" לא ייקרא כ"טירה". נבנה פעם אחת בטעינת המודול. */
const BY_LENGTH = [...IL_CITIES].sort((a, b) => b.length - a.length);

/* שם יישוב שנדבקה לו אות עברית מימין הוא מילה אחרת: "יהוד" שבתוך
   "יהודה ושומרון", "נתניה" שבתוך "נתניהו", "נשר" שבתוך "נשרף", "מיתר"
   שבתוך "מיתרים". הגבול נדרש מימין בלבד — משמאל דווקא נדבקות אותיות
   השימוש ("בתל אביב", "מחיפה", "ולירושלים"), ודרישת גבול גם שם הייתה
   מפילה את רוב ההתאמות. \b של JS אינו עוזר כאן: הוא מוגדר על אותיות
   לטיניות, ובין שתי אותיות עבריות אין בו גבול כלל. */
const cityRe = (/** @type {string} */ c) =>
	new RegExp(c.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '(?![\u05D0-\u05EA])');

const MATCHERS = BY_LENGTH.map((c) => /** @type {[string, RegExp]} */ ([c, cityRe(c)]));

/** @param {unknown} v */
const clean = (v) =>
	String(v ?? '')
		.replace(/\s+/g, ' ')
		.trim();

/**
 * כל היישובים שאפשר לזהות בטקסט חופשי אחד. כל התאמה נגרעת מהטקסט
 * לפני ההמשך, ולכן "מגדל העמק" אינו מייצר גם "מגדל".
 * @param {string} text
 * @param {Set<string>} into
 */
function scanText(text, into) {
	let rest = clean(text);
	if (!rest) return;
	for (const [city, re] of MATCHERS) {
		if (!re.test(rest)) continue;
		into.add(city);
		rest = rest.split(re).join(' ');
	}
}

/**
 * מנרמל ערך שהוקלד בשדה "עיר" אל שמו המוכר של היישוב, כשהוא מוכל בו —
 * כך ש"תל אביב יפו" ו"תל אביב" אינם שתי שורות נפרדות בבורר.
 * ערך שאינו מכיל אף יישוב מוכר נשמר כמות שהוא.
 * @param {string} raw
 */
export function canonicalCity(raw) {
	const v = clean(raw);
	if (!v) return '';
	return MATCHERS.find(([, re]) => re.test(v))?.[0] ?? v;
}

/**
 * הערים של כרטיסייה אחת: שדה "עיר" (כמו שהוא) בתוספת מה שנסרק מהכתובת
 * ומאזור השירות.
 * @param {{ city?: string, address?: string, salesArea?: string }} b
 * @returns {Set<string>}
 */
export function businessCities(b) {
	/** @type {Set<string>} */
	const out = new Set();
	const city = canonicalCity(b?.city ?? '');
	if (city) out.add(city);
	scanText(b?.address ?? '', out);
	scanText(b?.salesArea ?? '', out);
	return out;
}
