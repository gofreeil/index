/**
 * פונקציית תרגום לשפה הנוכחית של האתר: $bt('b_s1_title'), או עם
 * משתנים: $bt('b_step_n', { n: 2 }). מפתח שחסר בשפה נופל לעברית.
 */
export const bt = derived(lang, ($lang) => {
	const dict = adBuilderStrings[$lang] ?? adBuilderStrings.he;
	/**
	 * @param {string} key
	 * @param {Record<string, string | number>} [vars]
	 */
	return (key, vars) => {
		let s = dict[key] ?? adBuilderStrings.he[key] ?? key;
		if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
		return s;
	};
});
