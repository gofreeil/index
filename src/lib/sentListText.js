/**
 * הצבת ערכים בתבנית ({n}, {who}…). מפתח שלא הועבר נשאר גלוי כדי שתבנית שבורה
 * תיראה מיד.
 * @param {string} tpl @param {Record<string, string|number>} vars
 */
export const fill = (tpl, vars) =>
	String(tpl ?? '').replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
