// זיכרון קצר של התחום האחרון שנפתח במסילת דף הבית.
//
// למה הוא קיים: אל טופס הוספת העסק מגיעים מכמה דלתות — הקיצור "יש לכם
// עסק בתחום הזה?" (שנושא את התחום ב-?category=), אבל גם כפתור "הוסף עסק"
// הקבוע שבכותרת, שהוא קישור סטטי בלייאאוט ואינו יודע איזה תחום פתוח בדף.
// מי שגולש בתוך תחום ולוחץ על אחת הדלתות מצפה שהטופס כבר ידע איפה הוא
// היה — ולכן הבחירה נרשמת כאן, והטופס קורא אותה כברירת מחדל כשלא הגיע
// תחום מפורש בשאילתה.
//
// sessionStorage ולא localStorage: הזיכרון תחום לכרטיסייה הנוכחית — "המקום
// שממנו הגעת" הוא עניין של הגלישה הזו, לא העדפה קבועה שתצוץ שוב בעוד שבוע.
// ============================================================

const KEY = 'last-picked-category';

/** רישום התחום שנבחר במסילה; ערך ריק (ביטול הסינון) מוחק את הזיכרון.
 *  @param {string} name */
export function rememberCategory(name) {
	try {
		if (name) sessionStorage.setItem(KEY, name);
		else sessionStorage.removeItem(KEY);
	} catch {
		/* Safari במצב פרטי זורק — הקיצור בשאילתה עדיין עובד */
	}
}

/** התחום האחרון שנבחר, או מחרוזת ריקה */
export function recallCategory() {
	try {
		return sessionStorage.getItem(KEY) ?? '';
	} catch {
		return '';
	}
}
