// ============================================================
// terms.js — אישור תנאי הקהילה בידי בעל העסק
//
// המדריך פתוח רק לבעלי מקצוע שקיבלו על עצמם את תנאי הקהילה, ולכן אין
// כרטיסייה שיש לבעליה גישה אליה בלי חתימה. שתי הדרכים להיות בעל כרטיסייה:
//
//   /submit-business       הגשת עסק חדש — האישור הוא חלק מהטופס
//   דרישת בעלות            כרטיסייה קיימת: המשתמש דורש אותה, אדמין מאשר
//                          את הבקשה — ואז, לפני שהוא נכנס לעריכה בפעם
//                          הראשונה, הוא מקבל על עצמו את התנאים. השיוך
//                          עצמו אינו נותן גישה; השער הוא /business/[id]/edit
//
// למה השער שם ולא בבקשה עצמה: הבקשה עשויה להידחות, ואין טעם להחתים מי
// שלא יקבל את הכרטיסייה. החתימה נגבית מהבעלים בפועל, פעם אחת.
//
// שם השדה זהה בכל הטפסים, וכך גם הבדיקה בשרת. הבדיקה בדפדפן (required)
// היא נוחות בלבד: מקור-האמת הוא termsAccepted בשרת.
//
// מה נשמר על הכרטיסייה: accepted_terms (עמודה בוליאנית שקיימת באוסף)
// ומועד האישור ב-extra_fields.terms_accepted_at — לתאריך אין עמודה משלו,
// וזו אותה עמודת json שבה יושבים אימייל הבעלים, הסניפים והתגיות.
// ============================================================

export const TERMS_FIELD = 'accepted_terms';

/** מועד האישור, בתוך extra_fields */
export const TERMS_STAMP = 'terms_accepted_at';

/** קישור-עומק ללשונית "תנאי הקהילה" בדף המידע */
export const TERMS_LINK = '/policy#terms';

export const TERMS_ERROR = 'יש לאשר את תנאי הקהילה כדי להמשיך';

/** האם הטופס נשלח עם אישור התנאים. @param {FormData} fd */
export function termsAccepted(fd) {
	return fd.get(TERMS_FIELD) === 'on';
}

/**
 * האם על הכרטיסייה כבר רשום אישור. כרטיסייה שאין עליה — בעליה נעצר
 * בשער לפני העריכה, עד שיאשר.
 * @param {any} b רשומת idx-business
 */
export function hasAcceptedTerms(b) {
	return !!b?.accepted_terms;
}
